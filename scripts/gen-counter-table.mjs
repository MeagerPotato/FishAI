/**
 * gen-counter-table.mjs — extract the 9×9 payoff table the adaptive engine best-responds with.
 *
 * ```
 * node scripts/gen-counter-table.mjs [--artifact src/lab/data/style-results.v2.json]
 *                                    [--out lib/engine/bots/data/counter-table.ts]
 * ```
 *
 * Bass v1.0 chooses its style by best-responding to what it believes the opponents are playing,
 * and "best response" has to mean something measured, not something argued: the table it consults
 * is the full-precision matrix-v2 artifact (36 cells × 4,300 duplicate pairs, health-gated), the
 * same one the site renders at `?case=v2`. This script flattens that artifact into a committed
 * TypeScript constant so the policy layer stays platform-free and the provenance travels with the
 * number — the emitted file records the source artifact's `recordsDigest` and `engineCommit`, and
 * a reader who doubts a cell can re-run the lab and diff the digest.
 *
 * Two deliberate shape choices:
 *   - `p[i][j]` is the duplicate-averaged score rate of style i against style j, with the diagonal
 *     filled at 0.5 — unmeasured, known by symmetry (a style against itself on duplicate pairs is
 *     0.5 by construction; the lab does not spend games proving it).
 *   - The SE travels beside the score (`se[i][j]`, diagonal 0) so any consumer that wants to treat
 *     near-ties as ties can do so against the measured uncertainty instead of a magic epsilon.
 *
 * `scripts/` is linted but NOT typechecked, so this file only reads a file and writes a file; the
 * emitted constant is typechecked where it lands, and `tests/bots/adaptive.test.ts` pins its
 * antisymmetry (p[i][j] + p[j][i] ≈ 1) and its agreement with the committed artifact.
 */
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const [major, minor] = process.versions.node.split('.').map(Number)
if (major < 23 || (major === 23 && minor < 6)) {
  console.error(`node ${process.versions.node} cannot import TypeScript directly; run with Node 23.6+.`)
  process.exit(1)
}

function args(argv) {
  const out = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (!a.startsWith('--')) continue
    const eq = a.indexOf('=')
    if (eq > 0) out[a.slice(2, eq)] = a.slice(eq + 1)
    else if (i + 1 < argv.length && !argv[i + 1].startsWith('--')) out[a.slice(2)] = argv[++i]
    else out[a.slice(2)] = 'true'
  }
  return out
}

const opt = args(process.argv.slice(2))
const artifactPath = resolve(process.cwd(), opt.artifact ?? 'src/lab/data/style-results.v2.json')
const outPath = resolve(process.cwd(), opt.out ?? 'lib/engine/bots/data/counter-table.ts')

const artifact = JSON.parse(await readFile(artifactPath, 'utf8'))
if (artifact.meta?.schemaVersion !== 1) {
  console.error(`artifact ${artifactPath} has schemaVersion ${artifact.meta?.schemaVersion}, expected 1`)
  process.exit(2)
}
if (artifact.meta?.ruleSet !== 'us54') {
  console.error(`artifact rule set is ${artifact.meta?.ruleSet}, expected us54`)
  process.exit(2)
}

const styles = artifact.styles.map((s) => s.id)
const n = styles.length
const index = new Map(styles.map((id, i) => [id, i]))

const p = Array.from({ length: n }, (_, i) => Array.from({ length: n }, (_, j) => (i === j ? 0.5 : NaN)))
const se = Array.from({ length: n }, () => Array.from({ length: n }, () => 0))

for (const cell of artifact.matrix) {
  const i = index.get(cell.a)
  const j = index.get(cell.b)
  if (i === undefined || j === undefined) {
    console.error(`matrix cell ${cell.a}-vs-${cell.b} names a style missing from the roster`)
    process.exit(2)
  }
  if (!Number.isNaN(p[i][j])) {
    console.error(`pairing ${cell.a}-vs-${cell.b} appears twice in the artifact`)
    process.exit(2)
  }
  p[i][j] = cell.aScore
  p[j][i] = 1 - cell.aScore
  se[i][j] = cell.se
  se[j][i] = cell.se
}

for (let i = 0; i < n; i++)
  for (let j = 0; j < n; j++)
    if (Number.isNaN(p[i][j])) {
      console.error(`pairing ${styles[i]}-vs-${styles[j]} is missing from the artifact`)
      process.exit(2)
    }

// Sanity print: the best response to each pure style, read straight off the table.
for (let j = 0; j < n; j++) {
  let best = 0
  for (let i = 1; i < n; i++) if (p[i][j] > p[best][j]) best = i
  console.log(`BR(${styles[j].padEnd(9)}) = ${styles[best].padEnd(9)} at ${p[best][j].toFixed(4)}`)
}

const fmtRow = (row) => `    [${row.map((v) => String(Math.round(v * 1e6) / 1e6)).join(', ')}],`

const body = `/**
 * counter-table.ts — GENERATED by \`node scripts/gen-counter-table.mjs\`. Do not edit by hand.
 *
 * The measured 9×9 payoff table Bass v1.0 best-responds with. \`p[i][j]\` is the duplicate-
 * averaged score rate of \`styles[i]\` against \`styles[j]\` from the full-precision matrix-v2
 * artifact (36 cells × ${artifact.matrix[0].pairs.toLocaleString('en-US')} pairs, health-gated); the diagonal is 0.5 by duplicate-pair
 * symmetry, unmeasured on purpose. \`se[i][j]\` is the paired standard error of that cell
 * (diagonal 0). Provenance is exported beside the numbers: an adaptive decision is only as
 * honest as the matrix it consults, so the artifact digest travels with the table and
 * \`tests/bots/adaptive.test.ts\` pins the two against each other.
 */
import type { StyleId } from '../roster.ts'

export interface CounterTable {
  readonly styles: readonly StyleId[]
  /** p[i][j] = score rate of styles[i] vs styles[j]; antisymmetric about 0.5; diagonal 0.5. */
  readonly p: readonly (readonly number[])[]
  /** Paired SE of each off-diagonal cell; diagonal 0. */
  readonly se: readonly (readonly number[])[]
  readonly provenance: {
    readonly artifact: string
    readonly recordsDigest: string
    readonly engineCommit: string
    readonly generatedAt: string
    readonly pairsPerCell: number
  }
}

export const COUNTER_TABLE: CounterTable = {
  styles: [${styles.map((s) => `'${s}'`).join(', ')}],
  p: [
${p.map(fmtRow).join('\n')}
  ],
  se: [
${se.map(fmtRow).join('\n')}
  ],
  provenance: {
    artifact: 'style-results.v2.json',
    recordsDigest: '${artifact.meta.recordsDigest}',
    engineCommit: '${artifact.meta.engineCommit}',
    generatedAt: '${artifact.meta.generatedAt}',
    pairsPerCell: ${artifact.matrix[0].pairs},
  },
}
`

await mkdir(dirname(outPath), { recursive: true })
await writeFile(outPath, body, 'utf8')
console.log(`wrote ${outPath} (${styles.length} styles, ${artifact.matrix.length} cells)`)
