/**
 * Copy the rules engine's non-bot core into the room Edge Function's bundle.
 *
 *   node scripts/sync-room-engine.mjs          # copy, report what changed
 *   node scripts/sync-room-engine.mjs --check  # verify only, exit 1 on drift
 *
 * ## Why there is a copy at all
 *
 * The Edge Function is deployed by uploading a flat list of files to Supabase; it has no view
 * of this repository and cannot reach up out of `supabase/functions/room/` to import
 * `lib/engine/`. So the authority that decides every move in a shared room is a COPY of the
 * authority that decides every move in the solo table, and the entire safety of that
 * arrangement rests on the two being identical.
 *
 * A silently drifted copy is the worst failure this feature has available to it: the server
 * would enforce one rule set while every client explained a different one, and the disagreement
 * would surface as an unreproducible "the engine rejected my legal move" rather than as an
 * error anyone could find. So the copy is not maintained by hand. It is generated here, and
 * `tests/room/engine-copy.test.ts` fails the build if the generated bytes and `lib/engine/`
 * ever disagree.
 *
 * ## Why these nine modules and not `lib/engine/index.ts`
 *
 * `index.ts` re-exports `./bots/index.ts`, which is the larger part of the engine by volume and
 * exactly the part a room has no use for — the owner asked for six humans and no bots. Importing
 * the barrel would have pulled the whole bot roster, the adaptive tables and the bounded-memory
 * model into a function bundle that never calls any of them. The nine modules below are the
 * transitive closure of `newGame`/`reduce`/`publicView`/`seatView` and nothing else: every import
 * in them resolves to another member of the set, which is what makes a FLAT copy work.
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const from = join(root, 'lib', 'engine')
const to = join(root, 'supabase', 'functions', 'room', 'engine')

/**
 * The closure, in dependency order. Order is cosmetic — Deno resolves the graph itself — but it
 * documents the layering: pure data, then the deck, then the rest.
 */
export const ENGINE_MODULES = [
  'types.ts',
  'rng.ts',
  'cards.ts',
  'deal.ts',
  'variants.ts',
  'helpers.ts',
  'reduce.ts',
  'views.ts',
  'invariants.ts',
]

/** The header stamped onto every copy, above the original byte-for-byte. */
function banner(name) {
  return [
    '// GENERATED FILE — DO NOT EDIT.',
    `// Copied verbatim from lib/engine/${name} by scripts/sync-room-engine.mjs.`,
    '// Edit the original and re-run the script; tests/room/engine-copy.test.ts enforces the match.',
    '',
    '',
  ].join('\n')
}

/**
 * What the copy of `name` must contain, byte for byte. Exported so the test asserts against the
 * same function the script writes with, rather than against a second description of the rule
 * that could itself drift.
 */
export function expectedCopy(source, name) {
  return banner(name) + source
}

export function sourcePath(name) {
  return join(from, name)
}

export function copyPath(name) {
  return join(to, name)
}

function main() {
  const check = process.argv.includes('--check')
  mkdirSync(to, { recursive: true })

  // Anything in the target directory that is not in the closure is a leftover from an earlier
  // shape of the engine. In `--check` it is drift; in a real sync it is simply removed, because
  // a stale module that still resolves is precisely how a bundle keeps compiling against rules
  // that no longer exist.
  const stale = readdirSync(to).filter((f) => !ENGINE_MODULES.includes(f))

  const drifted = []
  for (const name of ENGINE_MODULES) {
    const want = expectedCopy(readFileSync(sourcePath(name), 'utf8'), name)
    let have = null
    try {
      have = readFileSync(copyPath(name), 'utf8')
    } catch {
      have = null
    }
    if (have === want) continue
    drifted.push(name)
    if (!check) writeFileSync(copyPath(name), want)
  }

  if (check) {
    const problems = [
      ...drifted.map((n) => `  drifted or missing: engine/${n}`),
      ...stale.map((n) => `  not part of the engine: engine/${n}`),
    ]
    if (problems.length > 0) {
      console.error('The room Edge Function\'s engine copy is out of date:\n' + problems.join('\n'))
      console.error('\nRun: node scripts/sync-room-engine.mjs')
      process.exit(1)
    }
    console.log(`engine copy is current — ${ENGINE_MODULES.length} modules match lib/engine/.`)
    return
  }

  for (const name of stale) rmSync(join(to, name), { recursive: true, force: true })

  const digest = createHash('sha256')
  for (const name of ENGINE_MODULES) digest.update(readFileSync(sourcePath(name)))

  console.log(
    drifted.length === 0
      ? `engine copy already current — ${ENGINE_MODULES.length} modules.`
      : `synced ${drifted.length} of ${ENGINE_MODULES.length} modules: ${drifted.join(', ')}`,
  )
  if (stale.length > 0) console.log(`removed ${stale.length} stale: ${stale.join(', ')}`)
  console.log(`lib/engine digest: ${digest.digest('hex').slice(0, 16)}`)
}

// Importable by the test without running the copy. `process.argv[1]` is the script only when it
// was invoked directly.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
